// «en:e322i», «E-150D», «е330» → «E322i», «E150d», «E330»; базовый код ищется, если нет точного.
window.lookupAdditive = (raw) => {
  const match = String(raw).replace(/[её]/gi, "e").match(/e\s*-?\s*(\d{3,4})\s*([a-z]?)/i);
  if (!match) return null;
  const entry = window.ADDITIVES[`E${match[1]}${match[2].toUpperCase()}`] || window.ADDITIVES[`E${match[1]}`];
  return { code: `E${match[1]}${match[2].toLowerCase()}`, entry };
};
